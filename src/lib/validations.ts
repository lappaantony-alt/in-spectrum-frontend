import { z } from 'zod';

export const nameSchema = z
  .string()
  .min(2, "Ім'я повинно містити щонайменше 2 символи")
  .regex(
    /^[a-zA-Zа-яА-ЯіІїЇєЄґҐ\s]+$/,
    "Ім'я може містити лише літери"
  );

export const phoneSchema = z
  .string()
  .min(7, 'Будь ласка, введіть коректний номер телефону')
  .regex(
    /^\+?[0-9]+$/,
    "Номер телефону може містити лише цифри та '+' на початку"
  );
